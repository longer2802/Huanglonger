// 完整流程實測（390px 手機寬度）
const { chromium } = require('playwright');
const fs = require('fs');
const BASE = process.env.BASE || 'http://localhost:4173/';
const OUT = 'shots/';
const log = (...a) => console.log(...a);
const assert = (c, m) => { if (!c) throw new Error('ASSERT: ' + m); log('  ✓', m); };

(async () => {
  const b = await chromium.launch({ env: { ...process.env, LANG: 'C.UTF-8', LC_ALL: 'C.UTF-8' } });
  const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 1, hasTouch: true, isMobile: true, acceptDownloads: true });
  const p = await ctx.newPage();
  const errs = []; p.on('pageerror', (e) => errs.push(e.message));
  p.on('dialog', (d) => d.accept());
  await p.goto(BASE, { waitUntil: 'networkidle' });

  log('1. 建立訂單＋上傳菜單辨識');
  await p.getByRole('button', { name: '＋ 開新訂單' }).click();
  await p.getByLabel('餐點店家').fill('幸福便當');
  await p.getByLabel('上傳餐點菜單照片').setInputFiles('e2e/fixtures/menu-bento.jpg');
  await p.getByRole('button', { name: '辨識', exact: true }).click();
  const dlg = p.getByRole('dialog', { name: '校對餐點候選清單' });
  await dlg.waitFor({ timeout: 120000 });
  // 校對：刪掉店名、修正分類
  await dlg.getByRole('button', { name: '刪除幸福便當' }).click();
  const cats = dlg.getByPlaceholder('分類');
  for (let i = 0; i < 5; i++) await cats.nth(i).fill('便當類');
  await p.screenshot({ path: OUT + 'm-proofread.png' });
  await dlg.getByRole('button', { name: '套用到菜單' }).click();
  const meal = p.getByRole('region', { name: '餐點菜單' });
  assert(await meal.getByText('1 項缺價').count() > 0, '套用後顯示滷肉飯缺價');
  await meal.getByRole('button', { name: /存成店家模板/ }).click();
  assert(await p.getByText(/還有 1 項缺價/).waitFor().then(() => true), '缺價時不能存模板');

  log('2. 飲料：貼上文字');
  await p.getByRole('checkbox', { name: '訂飲料' }).check();
  await p.getByLabel('飲料店家').fill('茶飲店');
  const drink = p.getByRole('region', { name: '飲料菜單' });
  await drink.getByRole('button', { name: '📋 貼上文字' }).click();
  await p.getByRole('textbox', { name: '菜單文字' }).fill('中杯 大杯\n紅茶 30 35\n珍珠奶茶 50 60\n【加料】\n珍珠 10');
  await p.getByRole('button', { name: '轉成品項' }).click();
  await p.getByRole('dialog', { name: '校對飲料候選清單' }).getByRole('button', { name: '套用到菜單' }).click();
  await drink.getByRole('button', { name: /存成店家模板/ }).click();
  assert(await p.getByText(/已存成模板「茶飲店」/).waitFor().then(() => true), '飲料店存成模板');
  await p.screenshot({ path: OUT + 'm-menu.png', fullPage: true });

  log('3. 名單');
  await p.getByRole('button', { name: /名單/ }).first().click();
  await p.getByText(/按手機鍵盤上的麥克風聽寫/).waitFor();
  assert(await p.getByTestId('speech-fallback').count() === 1, '語音不可用時顯示鍵盤聽寫與貼上說明，不顯示語音按鈕');
  assert(await p.getByRole('button', { name: /語音輸入/ }).count() === 0, '沒有 App 內語音按鈕');
  await p.getByLabel('同事名單').fill('阿榮\n小妤、小陳,小妤');
  await p.getByRole('button', { name: '預覽名單' }).click();
  assert(await p.getByText(/有同名的人/).count() === 1, '同名提示');
  await p.getByLabel('第4位辨識標記').fill('業務部');
  assert(await p.getByText(/有同名的人/).count() === 0, '加標記後不再同名');
  await p.getByRole('button', { name: /建立 4 人/ }).click();
  await p.screenshot({ path: OUT + 'm-people.png', fullPage: true });

  log('4. 點餐（手機摘要列＋展開編輯）');
  await p.getByRole('button', { name: '開始點餐 →' }).click();
  const card = (n) => p.getByTestId('person-card').filter({ hasText: n });
  // 缺價品項不能點
  await card('阿榮').getByRole('button').first().click();
  await p.getByRole('button', { name: '＋ 加餐點' }).click();
  assert(await p.getByRole('button', { name: /^滷肉飯/ }).count() === 0, '缺價的滷肉飯不在點餐選項');
  await p.getByRole('button', { name: /^雞腿便當/ }).click();
  await p.getByRole('button', { name: '加入' }).click();
  await p.getByRole('button', { name: '＋ 加飲料' }).click();
  await p.getByRole('button', { name: /^珍珠奶茶/ }).click();
  await p.getByRole('button', { name: /大杯 \$60/ }).click();
  await p.getByLabel('甜度').selectOption('半糖');
  await p.getByLabel('冰量').selectOption('少冰');
  await p.getByRole('button', { name: /珍珠 \+\$10/ }).click();
  await p.getByRole('button', { name: '加入' }).click();
  assert((await card('阿榮').innerText()).includes('$180'), '阿榮應收 110+60+10=180');
  await card('阿榮').locator('.person-sum').click();
  await card('小妤').first().locator('.person-sum').click();
  await p.getByRole('button', { name: '＋ 加餐點' }).click();
  await p.getByRole('button', { name: /^排骨便當/ }).click();
  await p.getByRole('button', { name: '增加' }).last().click();
  await p.getByLabel('客製備註（不影響價格）').fill('不要辣');
  await p.getByRole('button', { name: '加入' }).click();
  await p.getByRole('button', { name: '＋ 加飲料' }).click();
  await p.getByRole('button', { name: /^紅茶/ }).click();
  await p.getByRole('button', { name: /中杯 \$30/ }).click();
  await p.getByLabel('甜度').selectOption('無糖');
  await p.getByRole('button', { name: '加入' }).click();
  assert((await card('小妤').first().innerText()).includes('$220'), '小妤應收 95×2+30=220');
  await card('小妤').first().locator('.person-sum').click();
  await card('小陳').locator('.person-sum').click();
  await p.getByRole('checkbox', { name: '這次不訂' }).check();
  await card('小陳').locator('.person-sum').click();
  await p.screenshot({ path: OUT + 'm-order.png', fullPage: true });

  log('5. 重新整理後還原');
  await p.waitForTimeout(800);
  await p.reload({ waitUntil: 'networkidle' });
  assert((await card('阿榮').innerText()).includes('$180'), '重整後阿榮的點餐還在');
  assert((await card('小陳').innerText()).includes('不訂'), '重整後不訂狀態還在');

  log('6. 總計收款');
  await p.getByRole('button', { name: '總計收款 →' }).click();
  assert(await p.getByTestId('pending-panel').innerText().then((t) => t.includes('小妤（業務部）')), '列出待填人員');
  await p.getByTestId('pending-panel').getByRole('button', { name: '標記為不訂' }).click();
  assert(await p.getByTestId('pending-panel').count() === 0, '標記不訂後沒有待填');
  await p.getByLabel('阿榮 已收').check();
  const txt = async (id) => (await p.getByTestId(id).innerText()).trim();
  assert(await txt('vendor-total-meal') === '$300', '餐點店家合計 300');
  assert(await txt('vendor-total-drink') === '$100', '飲料店家合計 70+30=100');
  assert(await txt('grand-total') === '$400', '全單 400');
  assert(await txt('paid-total') === '$180' && await txt('unpaid-total') === '$220', '已收 180、待收 220');
  await p.getByRole('button', { name: '預覽核對' }).click();
  await p.getByRole('button', { name: '確認並儲存正式訂單' }).click();
  assert(await p.getByText('已確認並儲存為正式訂單').count() === 1, '確認後成為正式訂單');
  await p.screenshot({ path: OUT + 'm-totals.png', fullPage: true });

  log('7. 匯出');
  await p.getByRole('button', { name: '去匯出 →' }).click();
  await p.getByAltText('預覽第 1 頁').waitFor();
  await p.screenshot({ path: OUT + 'm-export.png', fullPage: true });
  const dl = async (name) => { const [d] = await Promise.all([p.waitForEvent('download'), p.getByRole('button', { name }).click()]); const path = OUT + d.suggestedFilename(); await d.saveAs(path); return path; };
  const png = await dl('下載 PNG');
  const pdf = await dl('下載 PDF');
  log('   files:', png, pdf);
  const date = new Date(); const iso = `${date.getFullYear()}-${String(date.getMonth() + 1).padStart(2, '0')}-${String(date.getDate()).padStart(2, '0')}`;
  assert(png.endsWith(`午餐_幸福便當_店家單_${iso}.png`), '店家單 PNG 檔名');
  assert(fs.readFileSync(pdf).slice(0, 5).toString() === '%PDF-', 'PDF 檔頭正確');
  await p.getByRole('button', { name: '內部收款' }).click();
  await p.waitForTimeout(500);
  const ipdf = await dl('下載 PDF');
  assert(ipdf.endsWith(`午餐_內部收款單_${iso}.pdf`), '內部收款 PDF 檔名');
  await p.getByRole('button', { name: '給店家' }).click();
  await p.getByLabel('選擇店家').selectOption({ label: '茶飲店（飲料）' });
  await p.waitForTimeout(500);
  const dpng = await dl('下載 PNG');
  assert(dpng.includes('茶飲店_店家單'), '飲料店家單 PNG');
  log('errors', errs);
  await b.close();
})().catch((e) => { console.error(e); process.exit(1); });
